# 3. 综合源的分发规则
# ------------------------------------------------------------
# 界面新闻、中新网这类综合站，一份数据要供多个分类。
# 处理方式：抓一次，然后给每条新闻「判定唯一归属」——
# 按 SHARED_CLASSIFY_ORDER 的顺序找关键词，第一个命中的分类胜出；
# 一个都不命中，就归到 SHARED_DEFAULT_CATEGORY（头条）。
#
# 为什么是「唯一归属」而不是「多分类都放」？
#   因为同一条新闻出现在三四个分类里，用户翻两下就会发现重复，
#   体验很差。宁可漏掉一点关联性，也不要重复。
#
# 【2026-10-05 启用了】新浪「全部」滚动流（sina_all）灌进来。
#   原因：中新网国际/娱乐两个频道是「编译短讯」为主，本身没配图，
#   在 REQUIRE_ORIGINAL_IMAGE=True 下 30 条只过得了 7 条；
#   而新浪滚动流每 5 分钟更新一次、文章页首图稳定可抓，
#   正好用来把这几个分类的条数补满。
SHARED_SOURCE_IDS = ["sina_all"]

# 顺序即优先级：娱乐最具体放最前，国内最宽泛放最后
SHARED_CLASSIFY_ORDER = ["娱乐", "社会", "国际", "国内"]
SHARED_DEFAULT_CATEGORY = "头条"

