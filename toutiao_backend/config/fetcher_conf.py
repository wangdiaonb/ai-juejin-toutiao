# 采集配置：从哪抓、怎么分到各分类、抓多少、什么时候抓
# ------------------------------------------------------------
# 结构分四块：
#   1. SOURCES        源池（每个源只定义一次、只抓一次）
#   2. CATEGORY_RULES 分类规则（哪个分类用哪些源、怎么筛）
#   3. 关键词表       判断一条新闻属于哪个分类
#   4. 参数与定时     条数、新鲜度、执行时间
#
# 【为什么要按「分类」来组织？】
#   早期版本只抓 AI 新闻，源和分类是写死的 1 对 1（4 个源 → 人工智能）。
#   现在要让 9 个分类都有数据，就必须解决两个问题：
#     ① 综合源（界面新闻、中新网）一份数据要分给多个分类；
#     ② 同一个源不能因为被多个分类引用就被重复抓 N 次。
#   所以把「源」和「分类」拆成两张表，中间用 id 关联：
#   先把所有源并发抓一遍，再按规则把结果分发到各个分类。
#
# 【重要教训：源会「假活着」】
#   新浪、搜狐、人民网的 RSS 都会返回 HTTP 200 和格式合法的 XML，
#   但内容停在 2016~2018 年 —— 站点早就停止更新了，feed 还挂在 CDN 上。
#   所以判断一个源能不能用，不能只看状态码，必须看 <pubDate> 距今天数。
#   这里配置的每一个源都经过 pubDate 实测，确认是当天/隔天更新的。
# ============================================================

