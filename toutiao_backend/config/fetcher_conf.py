PER_CATEGORY_LIMIT = 10       # 每个分类最多入库多少条（你要的「每天 10 条」）

# 每个分类先按 PER_CATEGORY_LIMIT × 这个倍数 取候选，补图后再筛到 10 条。
#
# 为什么需要它？因为 REQUIRE_ORIGINAL_IMAGE=True 时「没有原文图的条目会被丢弃」。
# 实测中新网只有约 40% 的文章在正文里带图，所以候选池必须显著大于 10，
# 否则丢完就只剩三五条。取 3.0（30 条）—— 正好是中新网每个频道 RSS 的全量，
# 按 40% 出图率算能凑出约 12 条有图的，够 10 条。
CANDIDATE_POOL_FACTOR = 3.0

# 只保留「最近多少小时内发布」的新闻。
