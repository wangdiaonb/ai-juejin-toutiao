# 5.1 内容是「原文摘录」而不是 AI 改写
# ------------------------------------------------------------
# True  = 直接用原文的标题 + 原文正文的摘录段（一字不改，零编造风险）
# False = 回到「大模型改写」的老路（services/llm_client.py）
#
# 为什么默认改成 True？
#   1. 真实。AI 改写再怎么约束也难免「顺手补一句」原文没有的话，
#      新闻客户端最怕的就是这个 —— 读者无法分辨哪句是原文、哪句是模型加的。
#   2. 快。一轮采集省掉 90 次大模型调用，整轮从 ~110 秒降到 ~20 秒。
#   3. 省钱。不再消耗 token。
#   代价是没有 AI 润色，标题会保留原文的「标题党」风格、正文里可能夹着
#   推广尾巴 —— 但那些是「原文就有的」，比模型编出来的可接受。
USE_LLM_REWRITE = False

# 原文摘录的长度（字符数）。
