# 5.3 澎湃新闻源（绕过 RSS，直接解析频道页内嵌 JSON）
# ------------------------------------------------------------
# 【为什么需要它？】
#   实测 2026 年中文主流新闻站已全面停用 RSS（新华/人民/央视/中青/光明/
#   观察者网/界面 的 RSS 全部 404，新浪的停在 8 年前）。
#   还活着的中新网 RSS 只有约 40% 的文章正文带图 ——
#   导致「国际」「娱乐」两个分类每天只能凑到 2~4 条。
#   澎湃是 Next.js 服务端渲染，频道页里嵌了完整的 JSON（含 pic 封面图），
#   实测**带图率 100%**，正好补上这个缺口。
#
# 【⚠️ 澎湃有腾讯云 WAF，必须低频访问】
#   实测并发 16 个请求打过去 → 几秒内 IP 被封，返回 403 拦截页且持续十几分钟。
#   所以 PP_INTERVAL 是硬性节流：任意两次请求之间强制间隔这么多秒（全局串行）。
#   不要为了「快」把它调小 —— 被封了整个源就废了，而且影响后续所有采集轮次。
